"""答题口径的**变体**。⛔ 与语言无关：语言跟题库走，变体跟**套件**走。

⚠️ 为什么必须有这一层：默认口径要求「资料里没有答案就弃权」，
而 N8 问的偏偏是**故意从语料里留出来、没见过的个体**——
⛔ 诚实弃权和归纳外推是**相反的要求**，一套提示不可能同时满足。
实测：`Zorp-H0 会不会发光` 在默认口径下答「资料未提及」，
而 N8 的解析器只认「是/否」，⛔ 四条臂全部 0.000——
那不是系统归纳不了，是尺子在量另一件事。

⭐ 公平性不受影响：**同一个套件内所有臂用同一个变体**，
而跨套件的分本来就不可比。

⚠️ 住在 core 是因为它是两边的共享词汇：套件声明自己要哪一种，
适配器照着换提示。⛔ 放 adapters 会让 suites 反过来依赖 adapters。
"""

from __future__ import annotations

from enum import Enum


class AnswerStyle(Enum):
    """套件对答题提出的要求。⛔ 一个套件内所有臂必须相同。"""

    #: 默认：⛔ 资料里没有就弃权，不许编。
    STRICT = "strict"
    #: ⭐ 允许按同类个例归纳出的规律外推——⚠️ 但资料里**明确写了**的以资料为准，
    #: 否则例外那一问（N8 的②）会被规律压过去。
    INDUCTIVE = "inductive"
