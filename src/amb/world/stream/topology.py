class FanTooWide(ValueError):
    """要的扇形度超过了配对池。⛔ 不静默取满多少算多少——
    ⚠️ 那会让 `fan64` 那一格其实只有 16 条，而**分数看上去很正常**。"""


def build(*, seed: int, fans: tuple[int, ...] = (1, 2, 4, 8, 16, 32, 64),
          entities_per_fan: int = 2, facts_per_fan: int = 16,
          cues_per_fact: int = 3) -> Topology:
    """每个扇形度造若干个实体，各挂 `fan` 条事实。

    ⚠️ 每条事实配 `cues_per_fact` 个线索：
    ⭐ 可达性 = 多少个线索够得到它；精确检索 = 指名要哪一条时 top-1 对不对。

    ⭐ 扇形度开到 64：[第一次跑](../../../../docs/runs/2026-09-03-native-suites-first.md)
    里 fan1~fan8 **全是 1.000**，只有 fan16 才开始有差别——
    ⛔ 一条前段全平的曲线量不出退化斜率。

    ⭐ `facts_per_fan` 是**每一档至少多少条事实**：低扇形度那几档靠加实体补齐。
    ⛔ 不补的话 fan1 只有 2 条观测、fan64 有 128 条——⚠️ 曲线两端的置信度差
    64 倍，而回归斜率把它们当同等看待。⭐ 低扇形度的事实很便宜
    （fan1 一个实体只占 1 条），补齐几乎不花语料。

    ⚠️ 代价说清楚：语料 62 → 288 条，`mem0` 摄入 +38 分钟，
    ⛔ 且语料指纹变了 → **全部摄入快照作废**，旧存档不可与新跑并列。
    """
    if max(fans) > len(PAIRS):
        raise FanTooWide(f"fan={max(fans)} 超过配对池 {len(PAIRS)} 对")
    rng = random.Random(seed)
    topo = Topology()

    for fan in fans:
        # ⭐ 够不够 facts_per_fan 条，不够就多造几个实体
        entities = max(entities_per_fan, -(-facts_per_fan // fan))
        for e in range(entities):
            # ⛔ 序号补零：⚠️ `E01_1` 是 `E01_10` 的前缀，
            # 实测让「实体沾边就全返回」那条对照策略在 fan1 上掉到 0.625——
            # ⭐ 那是名字撞的，不是扇形效应。等长就撞不上了。
            entity = f"E{fan:02d}_{e:02d}"
            picks = rng.sample(PAIRS, k=fan)
            for i, (verb, obj, alias) in enumerate(picks):
                fid = f"{entity}#{i}"
                topo.facts.append(Linked(
                    fid, entity, fan,
                    text=f"{entity} {verb} {obj}。",
                    # 三个线索，⭐ 各测一件事：
                    #   ① 实体+动词  —— 原文子串，指名道姓
                    #   ② 实体+别名  —— ⭐ **换个说法**，⛔ 一个字都不共
                    #   ③ 只有宾语    —— 线索不够，靠的是跨实体挤不挤得动
                    cues=(f"{entity} {verb}", f"{entity} {alias}",
                          obj)[:cues_per_fact],
                ))
    return topo
